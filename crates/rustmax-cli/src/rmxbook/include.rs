//! Expansion of mdbook's `{{#include}}` family of directives.
//!
//! This follows mdbook's own `links` preprocessor, which splices the named
//! file, or part of it, into the chapter before it is parsed as markdown:
//!
//! - `{{#include path}}` includes a whole file, `path:3` one line,
//!   `path:3:7` lines 3 through 7, `path:3:` and `path::7` open ranges,
//!   and `path:name` the lines between `ANCHOR: name` and `ANCHOR_END: name`.
//! - `{{#rustdoc_include path}}` takes the same selections, but keeps the
//!   rest of the file as hidden `# ` lines so the example still compiles.
//! - `{{#playground path attrs}}` includes a file as a Rust code block.
//! - `{{#title text}}` replaces the chapter title.
//! - `\{{#...}}` is an escape, rendered without the backslash.
//!
//! Included text is expanded recursively, relative to the included file.

use rmx::regex::{Captures, Regex};
use std::fs;
use std::ops::Range;
use std::path::Path;
use std::sync::LazyLock;

/// What replaces a directive from some other preprocessor, like Rust Forge's
/// `{{#installer_table}}`, whose content we can't produce.
const GENERATED_ELSEWHERE: &str = "<p class=\"generated-elsewhere\">Part of this page is \
    generated by the book's own build tooling, which the Rustmax library does not run. \
    See the upstream page, linked below.</p>";

/// Nesting deeper than this is assumed to be a cycle.
const MAX_DEPTH: usize = 10;

static LINK_RE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"\\\{\{#.*\}\}|\{\{\s*#([a-zA-Z0-9_]+)\s+([^}]+)\}\}").unwrap()
});

static ANCHOR_START: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"ANCHOR:\s*([\w_-]+)").unwrap());

static ANCHOR_END: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"ANCHOR_END:\s*([\w_-]+)").unwrap());

/// Expand every directive in a chapter.
///
/// `base` is the directory the chapter lives in. Returns the expanded text
/// and, if the chapter used `{{#title}}`, its replacement title.
///
/// A directive from some other preprocessor, alone on its line, is replaced
/// by a notice that the page is incomplete.
pub fn expand(content: &str, base: &Path) -> (String, Option<String>) {
    let mut title = None;
    let expanded = expand_at(content, base, 0, &mut title);
    let expanded = FOREIGN_RE.replace_all(&expanded, GENERATED_ELSEWHERE).into_owned();
    (expanded, title)
}

/// An argument-less directive alone on a line, like `{{#installer_table}}`.
static FOREIGN_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?m)^\{\{#[a-zA-Z0-9_]+\}\}[ \t]*$").unwrap());

fn expand_at(content: &str, base: &Path, depth: usize, title: &mut Option<String>) -> String {
    let mut out = String::with_capacity(content.len());
    let mut last = 0;

    for caps in LINK_RE.captures_iter(content) {
        let whole = caps.get(0).expect("group 0 always matches");
        let Some(replacement) = render(&caps, base, depth, title) else {
            continue;
        };

        out.push_str(&content[last..whole.start()]);
        // Included lines take on the indentation of the line holding the
        // directive, which keeps an include inside a list item in that item.
        let prefix = out.rsplit('\n').next().unwrap_or("").to_string();
        out.push_str(&replacement.lines().collect::<Vec<_>>().join(&format!("\n{prefix}")));
        last = whole.end();
    }

    out.push_str(&content[last..]);
    out
}

fn render(
    caps: &Captures<'_>,
    base: &Path,
    depth: usize,
    title: &mut Option<String>,
) -> Option<String> {
    let whole = caps.get(0).expect("group 0 always matches").as_str();
    if let Some(escaped) = whole.strip_prefix('\\') {
        return Some(escaped.to_string());
    }

    let kind = caps.get(1)?.as_str();
    let args = caps.get(2)?.as_str();

    if kind == "title" {
        *title = Some(args.trim().to_string());
        return Some(String::new());
    }

    let (path, selector, props) = parse_args(args)?;
    let target = base.join(&path);
    let text = match fs::read_to_string(&target) {
        Ok(text) => text,
        Err(e) => {
            eprintln!("  Warning: {whole}: cannot read {}: {e}", target.display());
            return None;
        }
    };

    let included = match kind {
        "include" => match selector.as_deref().map(parse_selector) {
            None => strip_anchor_lines(&text),
            Some(Selector::Lines(range)) => take_lines(&text, range),
            Some(Selector::Anchor(name)) => take_anchored_lines(&text, &name),
        },
        "rustdoc_include" => match selector.as_deref().map(parse_selector) {
            None => text.trim_end_matches('\n').to_string(),
            Some(Selector::Lines(range)) => take_rustdoc_lines(&text, range),
            Some(Selector::Anchor(name)) => take_rustdoc_anchored_lines(&text, &name),
        },
        "playground" | "playpen" => {
            let info = if props.is_empty() {
                "rust".to_string()
            } else {
                format!("rust,{}", props.join(","))
            };
            let text = text.trim_end_matches('\n');
            format!("```{info}\n{text}\n```\n")
        }
        _ => return None,
    };

    if depth >= MAX_DEPTH {
        eprintln!("  Warning: {whole}: includes nested too deeply; is there a cycle?");
        return Some(included);
    }
    let nested_base = target.parent().unwrap_or(base);
    Some(expand_at(&included, nested_base, depth + 1, title))
}

/// Split a directive's arguments into the path, the selector after the path's
/// first `:`, and any further whitespace-separated properties.
fn parse_args(args: &str) -> Option<(String, Option<String>, Vec<String>)> {
    let args = args.trim();
    if let Some(quoted) = args.strip_prefix('"') {
        let end = quoted.find('"')?;
        let path = quoted[..end].to_string();
        let rest = quoted[end + 1..].trim_start();
        let (selector, props) = match rest.strip_prefix(':') {
            Some(sel) => {
                let mut words = sel.split_whitespace();
                (words.next().map(str::to_string), words.map(str::to_string).collect())
            }
            None => (None, rest.split_whitespace().map(str::to_string).collect()),
        };
        return Some((path, selector, props));
    }

    let mut words = args.split_whitespace();
    let file_arg = words.next()?;
    let props = words.map(str::to_string).collect();
    let (path, selector) = match file_arg.split_once(':') {
        Some((path, selector)) => (path, Some(selector.to_string())),
        None => (file_arg, None),
    };
    Some((path.to_string(), selector, props))
}

enum Selector {
    /// Zero-based, end-exclusive line numbers.
    Lines(Range<usize>),
    Anchor(String),
}

fn parse_selector(selector: &str) -> Selector {
    let mut parts = selector.splitn(2, ':');
    let first = parts.next().unwrap_or("");
    let second = parts.next();

    let start = match first {
        "" => None,
        s => match s.parse::<usize>() {
            Ok(n) => Some(n.saturating_sub(1)),
            Err(_) => return Selector::Anchor(s.to_string()),
        },
    };
    let end = second.map(|s| s.parse::<usize>());

    Selector::Lines(match (start, end) {
        (Some(start), Some(Ok(end))) => start..end,
        (Some(start), Some(Err(_))) => start..usize::MAX,
        (Some(start), None) => start..start + 1,
        (None, Some(Ok(end))) => 0..end,
        (None, _) => 0..usize::MAX,
    })
}

/// A whole-file include, minus the anchor comments meant for other includes.
fn strip_anchor_lines(text: &str) -> String {
    text.lines()
        .filter(|l| !ANCHOR_START.is_match(l) && !ANCHOR_END.is_match(l))
        .collect::<Vec<_>>()
        .join("\n")
}

fn take_lines(text: &str, range: Range<usize>) -> String {
    text.lines()
        .skip(range.start)
        .take(range.end.saturating_sub(range.start))
        .collect::<Vec<_>>()
        .join("\n")
}

fn take_anchored_lines(text: &str, anchor: &str) -> String {
    let mut kept = Vec::new();
    let mut inside = false;
    for line in text.lines() {
        if inside {
            match ANCHOR_END.captures(line) {
                Some(caps) if &caps[1] == anchor => break,
                Some(_) => {}
                None if ANCHOR_START.is_match(line) => {}
                None => kept.push(line),
            }
        } else if ANCHOR_START.captures(line).is_some_and(|caps| &caps[1] == anchor) {
            inside = true;
        }
    }
    kept.join("\n")
}

fn take_rustdoc_lines(text: &str, range: Range<usize>) -> String {
    text.lines()
        .enumerate()
        .map(|(i, line)| {
            if range.contains(&i) {
                line.to_string()
            } else {
                format!("# {line}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn take_rustdoc_anchored_lines(text: &str, anchor: &str) -> String {
    let mut out = Vec::new();
    let mut inside = false;
    for line in text.lines() {
        if inside {
            match ANCHOR_END.captures(line) {
                Some(caps) if &caps[1] == anchor => inside = false,
                Some(_) => {}
                None if ANCHOR_START.is_match(line) => {}
                None => out.push(line.to_string()),
            }
        } else if ANCHOR_START.captures(line).is_some_and(|caps| &caps[1] == anchor) {
            inside = true;
        } else if !ANCHOR_END.is_match(line) {
            out.push(format!("# {line}"));
        }
    }
    out.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    use rmx::tempfile::TempDir;

    fn write(dir: &TempDir, rel: &str, contents: &str) {
        let path = dir.path().join(rel);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, contents).unwrap();
    }

    fn fixture() -> TempDir {
        let dir = rmx::tempfile::tempdir().unwrap();
        write(&dir,
            "code.rs",
            "use std::io;\n// ANCHOR: here\nfn main() {\n    // ANCHOR: inner\n    work();\n    // ANCHOR_END: inner\n}\n// ANCHOR_END: here\n",
        );
        write(&dir, "lines.txt", "one\ntwo\nthree\nfour\n");
        write(&dir, "sub/outer.md", "Outer {{#include inner.md}}\n");
        write(&dir, "sub/inner.md", "inner text");
        dir
    }

    #[test]
    fn test_whole_file_include_drops_anchor_comments() {
        let dir = fixture();
        let (out, _) = expand("{{#include code.rs}}", dir.path());
        assert_eq!(out, "use std::io;\nfn main() {\n    work();\n}");
    }

    #[test]
    fn test_line_ranges() {
        let dir = fixture();
        assert_eq!(expand("{{#include lines.txt:2}}", dir.path()).0, "two");
        assert_eq!(expand("{{#include lines.txt:2:3}}", dir.path()).0, "two\nthree");
        assert_eq!(expand("{{#include lines.txt:3:}}", dir.path()).0, "three\nfour");
        assert_eq!(expand("{{#include lines.txt::2}}", dir.path()).0, "one\ntwo");
    }

    #[test]
    fn test_anchor_include() {
        let dir = fixture();
        let (out, _) = expand("{{#include code.rs:here}}", dir.path());
        assert_eq!(out, "fn main() {\n    work();\n}");
    }

    /// Like mdbook, other anchors' start lines stay as hidden lines.
    #[test]
    fn test_rustdoc_include_hides_the_rest() {
        let dir = fixture();
        let (out, _) = expand("{{#rustdoc_include code.rs:inner}}", dir.path());
        assert_eq!(
            out,
            "# use std::io;\n# // ANCHOR: here\n# fn main() {\n    work();\n# }"
        );
    }

    #[test]
    fn test_nested_includes_resolve_relative_to_the_included_file() {
        let dir = fixture();
        let (out, _) = expand("{{#include sub/outer.md}}", dir.path());
        assert_eq!(out, "Outer inner text");
    }

    #[test]
    fn test_included_lines_take_the_directive_indentation() {
        let dir = fixture();
        let (out, _) = expand("- item\n\n  {{#include lines.txt::2}}", dir.path());
        assert_eq!(out, "- item\n\n  one\n  two");
    }

    #[test]
    fn test_escaped_directive_loses_its_backslash() {
        let dir = fixture();
        let (out, _) = expand(r"\{{#include file.rs}}", dir.path());
        assert_eq!(out, "{{#include file.rs}}");
    }

    #[test]
    fn test_playground_wraps_in_a_rust_block() {
        let dir = fixture();
        let (out, _) = expand("{{#playground lines.txt editable}}", dir.path());
        assert_eq!(out, "```rust,editable\none\ntwo\nthree\nfour\n```");
    }

    #[test]
    fn test_title() {
        let dir = fixture();
        let (out, title) = expand("{{#title A Better Title}}\nBody", dir.path());
        assert_eq!(out, "\nBody");
        assert_eq!(title.as_deref(), Some("A Better Title"));
    }

    #[test]
    fn test_unknown_directive_becomes_a_notice() {
        let dir = fixture();
        let (out, _) = expand("`{{#installer_table}}`\n\n{{#installer_table}}\n", dir.path());
        assert!(out.starts_with("`{{#installer_table}}`\n\n<p class=\"generated-elsewhere\">"), "{out}");
    }

    #[test]
    fn test_missing_file_is_left_in_place() {
        let dir = fixture();
        let (out, _) = expand("{{#include nope.rs}}", dir.path());
        assert_eq!(out, "{{#include nope.rs}}");
    }
}

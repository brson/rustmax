//! Procedural macros for the [`rustmax`] crate.
//!
//! This crate is an implementation detail of `rustmax`.
//! Use it through the `rmx` re-exports,
//! not as a direct dependency.
//!
//! [`rustmax`]: https://docs.rs/rustmax

use proc_macro::TokenStream;
use proc_macro2::{Ident, Literal, Span, TokenStream as TokenStream2, TokenTree};
use proc_macro_crate::{FoundCrate, crate_name};
use quote::{quote, quote_spanned};

